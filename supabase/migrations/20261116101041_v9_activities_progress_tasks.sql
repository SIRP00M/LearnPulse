create function private.check_window(p_from date, p_to date) returns void
language plpgsql immutable set search_path = '' as $$
begin
  if p_from is null or p_to is null or p_to < p_from or p_to - p_from + 1 > 62 then
    raise exception 'The date window must be 1-62 days' using errcode = 'PT400'; end if;
end $$;

create function private.check_limit(p_limit integer, p_max integer) returns void
language plpgsql immutable set search_path = '' as $$
begin
  if p_limit is null or p_limit < 1 or p_limit > p_max then
    raise exception 'The page size must be 1-% rows', p_max using errcode = 'PT400'; end if;
end $$;

-- Student: own occurrences in a window, keyset-paginated by (occurrence_date, activity_id).
create function public.get_my_activities(
  p_from date, p_to date, p_course_id uuid default null, p_limit integer default 200, p_cursor jsonb default null
) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_cd date := (p_cursor ->> 'date')::date;
  v_ca uuid := (p_cursor ->> 'activity_id')::uuid;
  v_rows jsonb;
  v_n integer;
  v_next jsonb;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if not exists (select 1 from public.profiles where id = v_uid and role = 'student') then
    raise exception 'Only students have this view' using errcode = 'PT403'; end if;
  perform private.check_window(p_from, p_to);
  perform private.check_limit(p_limit, 400);
  with mine as (
    select a.id, a.course_id, a.title, a.policy, c.title as course_title
      from public.activities a join public.course_members m on m.course_id = a.course_id
      join public.courses c on c.id = a.course_id
     where m.student_id = v_uid and m.status = 'active' and a.status <> 'archived' and c.status = 'active'
       and (p_course_id is null or a.course_id = p_course_id)),
  occ as (
    select mine.*, o.occurrence_date, o.timezone, o.deadline_mode, o.due_at as o_due
      from mine cross join lateral private.activity_occurrences(mine.id, p_from, p_to) o),
  rows_ as (
    select occ.id as activity_id, occ.course_id, occ.course_title, occ.title, occ.policy, occ.occurrence_date, occ.timezone,
           occ.deadline_mode, coalesce(c.due_at, occ.o_due) as due_at, c.status as completion_status, coalesce(c.version, 0) as version,
           c.note, c.reason,
           private.occurrence_state(c.status, occ.occurrence_date, occ.deadline_mode, occ.timezone, coalesce(c.due_at, occ.o_due)) as state
      from occ left join public.activity_completions c on c.activity_id = occ.id and c.student_id = v_uid
                                                       and c.occurrence_date = occ.occurrence_date
     where p_cursor is null or (occ.occurrence_date, occ.id) > (v_cd, v_ca)
     order by occ.occurrence_date, occ.id limit p_limit + 1)
  select coalesce(jsonb_agg(to_jsonb(r) order by r.occurrence_date, r.activity_id), '[]'::jsonb) into v_rows from rows_ r;
  v_n := jsonb_array_length(v_rows);
  if v_n > p_limit then
    v_rows := v_rows - p_limit;  -- drop the look-ahead row
    v_next := jsonb_build_object('date', v_rows -> (p_limit - 1) ->> 'occurrence_date', 'activity_id', v_rows -> (p_limit - 1) ->> 'activity_id');
  end if;
  return jsonb_build_object('items', v_rows, 'next_cursor', v_next, 'from', p_from, 'to', p_to);
end $$;

