-- V9 Daily Activity Tracker + Student Progress + Calendar/My Tasks reads. Purely additive: 4 new tables, new functions,
-- no change to any existing table, function, policy or grant (V3/V4/V6/V7 stay byte-identical).
--
-- MODEL
--   activities           one row per learning activity of a course; `policy` is immutable (it defines how history is read).
--   activity_schedules   IMMUTABLE, effective-dated versions: weekdays (ISO 1=Mon..7=Sun, empty = paused), effective_from,
--                        optional end_date, deadline_mode, IANA timezone. The occurrence on date d belongs to the version with the
--                        greatest effective_from <= d. Versions are never updated or deleted, so past eligibility never changes.
--   activity_completions one row per (activity, student, occurrence_date) when something was recorded. Occurrences themselves are
--                        VIRTUAL (generated by private.activity_occurrences); the deadline instant is snapshotted into the row.
--   activity_events      append-only audit + replay store (request_id unique, fingerprint of the parameters, stored response).
--
-- DEADLINES (deterministic)
--   An occurrence is a DATE in its schedule version's timezone.
--   deadline_mode 'day_end' (default): due_at = local midnight ending that date   = (date + 1) at time zone tz
--   deadline_mode 'time'             : due_at = date + deadline_time, local        = (date + time) at time zone tz
--   deadline_mode 'none'             : genuinely deadline-free: due_at is null, never 'missed', no streak.
--   Postgres resolves a local time inside a spring-forward gap to the offset before the change (02:30 -> 03:30) and a time that
--   occurs twice (fall back) to the LATER (standard-time) instant; both measured on Postgres 17.6 and pinned by tests.
--
-- STATES  occurrence: upcoming | open | pending | completed | rejected | not_done | missed
--   completed = teacher_marked | self_reported | approved; pending = awaiting teacher verification; rejected stays resubmittable
--   until due_at; not_done = explicit teacher decision (breaks a streak); missed = deadline passed with nothing credited.
-- STREAK  over the last 62 days of eligible occurrences: completed extends, missed/not_done breaks, upcoming / open (today) /
--   pending / still-resubmittable rejected are neutral. Judged by server submit time, never approval time. Unscheduled days never count.
--
-- Every mutation: security definer RPC, request_id replay (PT409 when the id is reused for different content), version checks.
-- Errors: PT400 invalid input, PT401 not authenticated, PT403 not allowed for this role/policy, PT404 not found OR not authorised
-- (same answer: no existence leak), PT409 state conflict. Limits: window <= 62 days, <= 400 rows per page, <= 25 active activities
-- per course, <= 20 schedule versions per activity, pending page <= 50.

-- Tables ---------------------------------------------------------------------------------------------
create table public.activities (
  id uuid primary key default gen_random_uuid(),
  course_id uuid not null references public.courses (id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  description text not null default '' check (char_length(description) <= 2000),
  policy text not null check (policy in ('teacher_marked', 'self_reported', 'teacher_verified')),
  status text not null default 'active' check (status in ('active', 'inactive', 'archived')),
  version integer not null default 1,
  request_id uuid not null unique,
  created_by uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index activities_course_idx on public.activities (course_id, status, created_at);

create table public.activity_schedules (
  id uuid primary key default gen_random_uuid(),
  activity_id uuid not null references public.activities (id) on delete cascade,
  version_no integer not null check (version_no >= 1),
  weekdays smallint[] not null check (weekdays <@ array[1, 2, 3, 4, 5, 6, 7]::smallint[]),
  effective_from date not null,
  end_date date,
  deadline_mode text not null default 'day_end' check (deadline_mode in ('day_end', 'time', 'none')),
  deadline_time time,
  timezone text not null default 'Asia/Bangkok',
  request_id uuid not null unique,
  created_by uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (activity_id, version_no),
  unique (activity_id, effective_from),
  check ((deadline_mode = 'time') = (deadline_time is not null)),
  check (end_date is null or end_date >= effective_from)
);

create table public.activity_completions (
  activity_id uuid not null references public.activities (id) on delete cascade,
  student_id uuid not null references public.profiles (id) on delete cascade,
  occurrence_date date not null,
  status text not null check (status in ('teacher_marked', 'self_reported', 'pending', 'approved', 'rejected', 'not_done')),
  schedule_version integer not null,
  due_at timestamptz,
  submitted_at timestamptz,
  decided_by uuid references public.profiles (id) on delete set null,
  decided_at timestamptz,
  reason text not null default '' check (char_length(reason) <= 500),
  note text not null default '' check (char_length(note) <= 500),
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (activity_id, student_id, occurrence_date)
);
create index activity_completions_student_idx on public.activity_completions (student_id, occurrence_date);
create index activity_completions_pending_idx on public.activity_completions (activity_id, submitted_at) where status = 'pending';

create table public.activity_events (
  id uuid primary key default gen_random_uuid(),
  activity_id uuid not null references public.activities (id) on delete cascade,
  student_id uuid references public.profiles (id) on delete cascade,
  occurrence_date date,
  actor_id uuid not null references public.profiles (id) on delete cascade,
  action text not null check (action in ('created', 'schedule_added', 'status_changed', 'updated', 'self_completed', 'submitted',
                                         'marked', 'corrected', 'approved', 'rejected', 'retracted')),
  old_status text,
  new_status text,
  note text not null default '',
  version_after integer not null,
  fingerprint text not null,
  request_id uuid not null unique,
  response jsonb not null,
  created_at timestamptz not null default now()
);
create index activity_events_activity_idx on public.activity_events (activity_id, created_at);

-- Authorization helpers (private schema: usable by RLS, not reachable through the API) -----------------
create function private.is_activity_owner(p_activity_id uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.activities a join public.courses c on c.id = a.course_id
                  where a.id = p_activity_id and c.owner_id = (select auth.uid()))
$$;

create function private.is_activity_member(p_activity_id uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.activities a join public.course_members m on m.course_id = a.course_id
                  where a.id = p_activity_id and m.student_id = (select auth.uid()) and m.status = 'active'
                    and a.status <> 'archived')
$$;

do $$
declare
  f text;
begin
  foreach f in array array['private.is_activity_owner(uuid)', 'private.is_activity_member(uuid)'] loop
    execute format('revoke all on function %s from public, anon, authenticated, service_role', f);
    execute format('grant execute on function %s to authenticated', f);
  end loop;
end $$;

alter table public.activities enable row level security;
alter table public.activity_schedules enable row level security;
alter table public.activity_completions enable row level security;
alter table public.activity_events enable row level security;

create policy activities_select on public.activities for select to authenticated
  using (private.is_activity_owner(id) or private.is_activity_member(id));
create policy activity_schedules_select on public.activity_schedules for select to authenticated
  using (private.is_activity_owner(activity_id) or private.is_activity_member(activity_id));
create policy activity_completions_select on public.activity_completions for select to authenticated
  using (private.is_activity_owner(activity_id)
         or (student_id = (select auth.uid()) and private.is_activity_member(activity_id)));
create policy activity_events_select on public.activity_events for select to authenticated
  using (private.is_activity_owner(activity_id));

grant select on public.activities, public.activity_schedules, public.activity_completions, public.activity_events to authenticated;

-- Pure helpers (invoked inside the definer RPCs below; no table access beyond the schedule lookup) -------
-- Virtual occurrences of one activity between two dates, with the deadline instant of the version in force.
create function private.activity_occurrences(p_activity_id uuid, p_from date, p_to date)
returns table (occurrence_date date, schedule_version integer, timezone text, deadline_mode text, due_at timestamptz)
language sql stable set search_path = '' as $$
  select d.d, x.version_no, x.timezone, x.deadline_mode,
         case x.deadline_mode
           when 'time' then (d.d + x.deadline_time)::timestamp at time zone x.timezone
           when 'day_end' then (d.d + 1)::timestamp at time zone x.timezone
         end
    from generate_series(p_from::timestamp, p_to::timestamp, interval '1 day') g(ts)
   cross join lateral (select g.ts::date as d) d
    join lateral (select s.* from public.activity_schedules s
                   where s.activity_id = p_activity_id and s.effective_from <= d.d
                   order by s.effective_from desc limit 1) x on true
   where (x.end_date is null or d.d <= x.end_date)
     and extract(isodow from d.d)::smallint = any (x.weekdays)
$$;

-- Occurrence state from the recorded status (null = nothing recorded). The same function feeds every screen and RPC.
create function private.occurrence_state(p_completion text, p_date date, p_mode text, p_tz text, p_due timestamptz)
returns text language sql stable set search_path = '' as $$
  select case
    when p_completion in ('self_reported', 'teacher_marked', 'approved') then 'completed'
    when p_completion = 'pending' then 'pending'
    when p_completion = 'not_done' then 'not_done'
    when p_completion = 'rejected' then case when p_mode = 'none' or now() <= p_due then 'rejected' else 'missed' end
    when p_date > (now() at time zone p_tz)::date then 'upcoming'
    when p_mode = 'none' or now() <= p_due then 'open'
    else 'missed' end
$$;

-- One definition of an assignment's task status (V7 semantics: returned is not done; overdue = past due and never submitted).
create function private.assignment_task_status(p_submission text, p_due timestamptz)
returns text language sql stable set search_path = '' as $$
  select case
    when p_submission = 'returned' then 'needs_revision'
    when p_submission = 'graded' then 'graded'
    when p_submission = 'submitted' then 'awaiting_review'
    when p_due is not null and p_due < now() then 'overdue'
    else 'todo' end
$$;

create function private.activity_streak(p_activity_id uuid, p_student_id uuid) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  v_first date;
  v_tz text;
  v_mode text;
  v_today date;
  v_from date;
  r record;
  v_current integer := 0;
  v_best integer := 0;
  v_run integer := 0;
  v_done integer := 0;
  v_resolved integer := 0;
  v_broken boolean := false;
begin
  select min(effective_from) into v_first from public.activity_schedules where activity_id = p_activity_id;
  select s.timezone, s.deadline_mode into v_tz, v_mode from public.activity_schedules s
   where s.activity_id = p_activity_id order by s.effective_from desc limit 1;
  if v_first is null then
    return jsonb_build_object('current', 0, 'best', 0, 'completed', 0, 'resolved', 0, 'window_days', 62, 'capped', false);
  end if;
  v_today := (now() at time zone v_tz)::date;
  v_from := greatest(v_first, v_today - 61);
  for r in
    select o.occurrence_date,
           private.occurrence_state(c.status, o.occurrence_date, o.deadline_mode, o.timezone, coalesce(c.due_at, o.due_at)) as st
      from private.activity_occurrences(p_activity_id, v_from, v_today) o
      left join public.activity_completions c on c.activity_id = p_activity_id and c.student_id = p_student_id
                                              and c.occurrence_date = o.occurrence_date
     order by o.occurrence_date desc
  loop
    if r.st = 'completed' then
      v_done := v_done + 1; v_resolved := v_resolved + 1; v_run := v_run + 1;
      if not v_broken then v_current := v_current + 1; end if;
      v_best := greatest(v_best, v_run);
    elsif r.st in ('missed', 'not_done') then
      v_resolved := v_resolved + 1; v_broken := true; v_run := 0;
    end if;  -- upcoming / open / pending / rejected (still open): neutral
  end loop;
  return jsonb_build_object(
    'current', case when v_mode = 'none' then null else v_current end,
    'best', case when v_mode = 'none' then null else v_best end,
    'completed', v_done, 'resolved', v_resolved, 'window_days', 62,
    'capped', (v_first < v_today - 61) and not v_broken);
end $$;

-- Mutations ------------------------------------------------------------------------------------------
create function private.check_weekdays(p_weekdays smallint[], p_allow_empty boolean) returns void
language plpgsql immutable set search_path = '' as $$
begin
  if p_weekdays is null or (cardinality(p_weekdays) = 0 and not p_allow_empty)
     or (select count(distinct w) from unnest(p_weekdays) w) <> cardinality(p_weekdays)
     or not (p_weekdays <@ array[1, 2, 3, 4, 5, 6, 7]::smallint[]) then
    raise exception 'Choose one or more distinct weekdays (1 = Monday ... 7 = Sunday)' using errcode = 'PT400';
  end if;
end $$;

create function private.check_deadline(p_mode text, p_time time, p_tz text) returns void
language plpgsql stable set search_path = '' as $$
begin
  if p_mode not in ('day_end', 'time', 'none') or (p_mode = 'time') <> (p_time is not null) then
    raise exception 'Deadline mode must be day_end, time (with a time) or none' using errcode = 'PT400'; end if;
  if p_tz is null or not exists (select 1 from pg_timezone_names where name = p_tz) then
    raise exception 'Unknown timezone' using errcode = 'PT400'; end if;
end $$;

create function public.create_activity(
  p_course_id uuid, p_request_id uuid, p_title text, p_description text, p_policy text,
  p_weekdays smallint[], p_start_date date, p_end_date date default null,
  p_deadline_mode text default 'day_end', p_deadline_time time default null, p_timezone text default 'Asia/Bangkok'
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_title text := btrim(coalesce(p_title, ''));
  v_desc text := btrim(coalesce(p_description, ''));
  v_course public.courses;
  v_ev public.activity_events;
  v_a public.activities;
  v_fp text;
  v_today date;
  v_response jsonb;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if p_request_id is null then raise exception 'Request id required' using errcode = 'PT400'; end if;
  v_fp := md5(concat_ws('|', p_course_id, v_title, v_desc, p_policy, array_to_string(p_weekdays, ','), p_start_date, p_end_date,
                        p_deadline_mode, p_deadline_time, p_timezone));
  select * into v_course from public.courses where id = p_course_id and owner_id = v_uid for update;
  if not found then raise exception 'Course not found' using errcode = 'PT404'; end if;

  select * into v_ev from public.activity_events where request_id = p_request_id;
  if found then
    if v_ev.actor_id <> v_uid or v_ev.fingerprint <> v_fp or v_ev.action <> 'created' then
      raise exception 'Request id was already used for different content' using errcode = 'PT409'; end if;
    return v_ev.response || jsonb_build_object('replayed', true);
  end if;

  if v_course.status <> 'active' then raise exception 'Course is archived' using errcode = 'PT409'; end if;
  if char_length(v_title) not between 1 and 120 then raise exception 'Title must be 1-120 characters' using errcode = 'PT400'; end if;
  if char_length(v_desc) > 2000 then raise exception 'Description is too long' using errcode = 'PT400'; end if;
  if p_policy is null or p_policy not in ('teacher_marked', 'self_reported', 'teacher_verified') then
    raise exception 'Unknown completion policy' using errcode = 'PT400'; end if;
  perform private.check_weekdays(p_weekdays, false);
  perform private.check_deadline(p_deadline_mode, p_deadline_time, p_timezone);
  v_today := (now() at time zone p_timezone)::date;
  if p_start_date is null or p_start_date < v_today or p_start_date > v_today + 365 then
    raise exception 'Start date must be today or within the next year' using errcode = 'PT400'; end if;
  if p_end_date is not null and (p_end_date < p_start_date or p_end_date > p_start_date + 1095) then
    raise exception 'End date must be after the start date (at most 3 years)' using errcode = 'PT400'; end if;
  if (select count(*) from public.activities where course_id = p_course_id and status = 'active') >= 25 then
    raise exception 'This course reached the 25 active activity limit' using errcode = 'PT409'; end if;

  insert into public.activities (course_id, title, description, policy, request_id, created_by)
  values (p_course_id, v_title, v_desc, p_policy, p_request_id, v_uid) returning * into v_a;
  insert into public.activity_schedules (activity_id, version_no, weekdays, effective_from, end_date, deadline_mode, deadline_time,
                                         timezone, request_id, created_by)
  values (v_a.id, 1, p_weekdays, p_start_date, p_end_date, p_deadline_mode, p_deadline_time, p_timezone, p_request_id, v_uid);
  v_response := jsonb_build_object('id', v_a.id, 'version', v_a.version, 'status', v_a.status, 'policy', v_a.policy, 'schedule_version', 1);
  insert into public.activity_events (activity_id, actor_id, action, new_status, version_after, fingerprint, request_id, response)
  values (v_a.id, v_uid, 'created', v_a.status, v_a.version, v_fp, p_request_id, v_response);
  return v_response;
end $$;

create function public.update_activity(
  p_activity_id uuid, p_request_id uuid, p_expected_version integer, p_title text, p_description text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_title text := btrim(coalesce(p_title, ''));
  v_desc text := btrim(coalesce(p_description, ''));
  v_a public.activities;
  v_ev public.activity_events;
  v_fp text := md5(concat_ws('|', p_activity_id, p_expected_version, btrim(coalesce(p_title, '')), btrim(coalesce(p_description, ''))));
  v_response jsonb;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if p_request_id is null then raise exception 'Request id required' using errcode = 'PT400'; end if;
  select a.* into v_a from public.activities a join public.courses c on c.id = a.course_id
   where a.id = p_activity_id and c.owner_id = v_uid for update of a;
  if not found then raise exception 'Activity not found' using errcode = 'PT404'; end if;
  select * into v_ev from public.activity_events where request_id = p_request_id;
  if found then
    if v_ev.actor_id <> v_uid or v_ev.fingerprint <> v_fp or v_ev.action <> 'updated' then
      raise exception 'Request id was already used for different content' using errcode = 'PT409'; end if;
    return v_ev.response || jsonb_build_object('replayed', true);
  end if;
  if v_a.version <> p_expected_version then raise exception 'This activity changed; reload' using errcode = 'PT409'; end if;
  if char_length(v_title) not between 1 and 120 then raise exception 'Title must be 1-120 characters' using errcode = 'PT400'; end if;
  if char_length(v_desc) > 2000 then raise exception 'Description is too long' using errcode = 'PT400'; end if;
  update public.activities set title = v_title, description = v_desc, version = version + 1, updated_at = now()
   where id = p_activity_id returning * into v_a;
  v_response := jsonb_build_object('id', v_a.id, 'version', v_a.version, 'status', v_a.status);
  insert into public.activity_events (activity_id, actor_id, action, version_after, fingerprint, request_id, response)
  values (p_activity_id, v_uid, 'updated', v_a.version, v_fp, p_request_id, v_response);
  return v_response;
end $$;

-- A schedule change is a NEW immutable version that starts no earlier than tomorrow in both the old and the new timezone.
create function public.add_activity_schedule(
  p_activity_id uuid, p_request_id uuid, p_expected_version integer, p_weekdays smallint[], p_effective_from date,
  p_end_date date default null, p_deadline_mode text default 'day_end', p_deadline_time time default null,
  p_timezone text default 'Asia/Bangkok'
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_a public.activities;
  v_last public.activity_schedules;
  v_ev public.activity_events;
  v_fp text := md5(concat_ws('|', p_activity_id, p_expected_version, array_to_string(p_weekdays, ','), p_effective_from, p_end_date,
                             p_deadline_mode, p_deadline_time, p_timezone));
  v_earliest date;
  v_n integer;
  v_response jsonb;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if p_request_id is null then raise exception 'Request id required' using errcode = 'PT400'; end if;
  select a.* into v_a from public.activities a join public.courses c on c.id = a.course_id
   where a.id = p_activity_id and c.owner_id = v_uid for update of a;
  if not found then raise exception 'Activity not found' using errcode = 'PT404'; end if;
  select * into v_ev from public.activity_events where request_id = p_request_id;
  if found then
    if v_ev.actor_id <> v_uid or v_ev.fingerprint <> v_fp or v_ev.action <> 'schedule_added' then
      raise exception 'Request id was already used for different content' using errcode = 'PT409'; end if;
    return v_ev.response || jsonb_build_object('replayed', true);
  end if;
  if v_a.version <> p_expected_version then raise exception 'This activity changed; reload' using errcode = 'PT409'; end if;
  if v_a.status = 'archived' then raise exception 'Activity is archived' using errcode = 'PT409'; end if;
  if not exists (select 1 from public.courses where id = v_a.course_id and status = 'active') then
    raise exception 'Course is archived' using errcode = 'PT409'; end if;
  perform private.check_weekdays(p_weekdays, true);
  perform private.check_deadline(p_deadline_mode, p_deadline_time, p_timezone);
  select * into v_last from public.activity_schedules where activity_id = p_activity_id order by effective_from desc limit 1;
  v_earliest := greatest((now() at time zone v_last.timezone)::date, (now() at time zone p_timezone)::date) + 1;
  if p_effective_from is null or p_effective_from < v_earliest or p_effective_from <= v_last.effective_from
     or p_effective_from > v_earliest + 730 then
    raise exception 'A schedule change starts tomorrow or later, after the previous change' using errcode = 'PT409'; end if;
  if p_end_date is not null and p_end_date < p_effective_from then
    raise exception 'End date must not precede the start' using errcode = 'PT400'; end if;
  select count(*) into v_n from public.activity_schedules where activity_id = p_activity_id;
  if v_n >= 20 then raise exception 'This activity reached the 20 schedule version limit' using errcode = 'PT409'; end if;

  insert into public.activity_schedules (activity_id, version_no, weekdays, effective_from, end_date, deadline_mode, deadline_time,
                                         timezone, request_id, created_by)
  values (p_activity_id, v_n + 1, p_weekdays, p_effective_from, p_end_date, p_deadline_mode, p_deadline_time, p_timezone,
          p_request_id, v_uid);
  update public.activities set version = version + 1, updated_at = now() where id = p_activity_id returning * into v_a;
  v_response := jsonb_build_object('id', p_activity_id, 'version', v_a.version, 'schedule_version', v_n + 1);
  insert into public.activity_events (activity_id, actor_id, action, version_after, fingerprint, request_id, response)
  values (p_activity_id, v_uid, 'schedule_added', v_a.version, v_fp, p_request_id, v_response);
  return v_response;
end $$;

-- active <-> inactive writes a schedule version (pause = empty weekdays, resume = the last non-empty settings); archive is a flag.
create function public.set_activity_status(
  p_activity_id uuid, p_request_id uuid, p_expected_version integer, p_status text, p_effective_from date default null
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_a public.activities;
  v_last public.activity_schedules;
  v_prev public.activity_schedules;
  v_ev public.activity_events;
  v_fp text := md5(concat_ws('|', p_activity_id, p_expected_version, p_status, p_effective_from));
  v_old text;
  v_n integer;
  v_response jsonb;
  v_earliest date;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if p_request_id is null then raise exception 'Request id required' using errcode = 'PT400'; end if;
  if p_status is null or p_status not in ('active', 'inactive', 'archived') then
    raise exception 'Unknown status' using errcode = 'PT400'; end if;
  select a.* into v_a from public.activities a join public.courses c on c.id = a.course_id
   where a.id = p_activity_id and c.owner_id = v_uid for update of a;
  if not found then raise exception 'Activity not found' using errcode = 'PT404'; end if;
  select * into v_ev from public.activity_events where request_id = p_request_id;
  if found then
    if v_ev.actor_id <> v_uid or v_ev.fingerprint <> v_fp or v_ev.action <> 'status_changed' then
      raise exception 'Request id was already used for different content' using errcode = 'PT409'; end if;
    return v_ev.response || jsonb_build_object('replayed', true);
  end if;
  if v_a.version <> p_expected_version then raise exception 'This activity changed; reload' using errcode = 'PT409'; end if;
  if v_a.status = p_status then raise exception 'The activity already has this status' using errcode = 'PT409'; end if;
  if not exists (select 1 from public.courses where id = v_a.course_id and status = 'active') then
    raise exception 'Course is archived' using errcode = 'PT409'; end if;
  v_old := v_a.status;
  select * into v_last from public.activity_schedules where activity_id = p_activity_id order by effective_from desc limit 1;
  if p_status = 'archived' then
    null;
  elsif p_status = 'inactive' and v_old = 'archived' then
    null;  -- unarchive: stays paused until resumed
  else
    v_earliest := (now() at time zone v_last.timezone)::date + 1;
    if p_effective_from is null or p_effective_from < v_earliest or p_effective_from <= v_last.effective_from then
      raise exception 'The change starts tomorrow or later, after the previous schedule change' using errcode = 'PT409'; end if;
    select count(*) into v_n from public.activity_schedules where activity_id = p_activity_id;
    if v_n >= 20 then raise exception 'This activity reached the 20 schedule version limit' using errcode = 'PT409'; end if;
    if p_status = 'active' then
      if (select count(*) from public.activities where course_id = v_a.course_id and status = 'active') >= 25 then
        raise exception 'This course reached the 25 active activity limit' using errcode = 'PT409'; end if;
      select * into v_prev from public.activity_schedules
       where activity_id = p_activity_id and cardinality(weekdays) > 0 order by effective_from desc limit 1;
      if not found then raise exception 'There is no earlier schedule to resume' using errcode = 'PT409'; end if;
      insert into public.activity_schedules (activity_id, version_no, weekdays, effective_from, end_date, deadline_mode, deadline_time,
                                             timezone, request_id, created_by)
      values (p_activity_id, v_n + 1, v_prev.weekdays, p_effective_from, null, v_prev.deadline_mode, v_prev.deadline_time,
              v_prev.timezone, p_request_id, v_uid);
    else  -- inactive: pause
      insert into public.activity_schedules (activity_id, version_no, weekdays, effective_from, end_date, deadline_mode, deadline_time,
                                             timezone, request_id, created_by)
      values (p_activity_id, v_n + 1, '{}', p_effective_from, null, v_last.deadline_mode, v_last.deadline_time,
              v_last.timezone, p_request_id, v_uid);
    end if;
  end if;
  update public.activities set status = p_status, version = version + 1, updated_at = now()
   where id = p_activity_id returning * into v_a;
  v_response := jsonb_build_object('id', p_activity_id, 'version', v_a.version, 'status', v_a.status);
  insert into public.activity_events (activity_id, actor_id, action, old_status, new_status, version_after, fingerprint, request_id, response)
  values (p_activity_id, v_uid, 'status_changed', v_old, p_status, v_a.version, v_fp, p_request_id, v_response);
  return v_response;
end $$;

