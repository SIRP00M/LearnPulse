-- Unified student tasks (derived, never stored). Views: range | upcoming | overdue | completed. Keyset pages <= 400.
create function private.student_task_pool(p_uid uuid, p_view text, p_from timestamptz, p_to timestamptz, p_from_date date, p_to_date date)
returns table (kind text, id uuid, key2 text, course_id uuid, course_title text, title text, status text, task_at timestamptz,
               due_at timestamptz, occurrence_date date, policy text, version integer, sort_at timestamptz)
language sql stable set search_path = '' as $$
  with courses_ as (
    select c.id, c.title from public.course_members m join public.courses c on c.id = m.course_id
     where m.student_id = p_uid and m.status = 'active' and c.status = 'active'),
  asg as (
    select 'assignment'::text as kind, a.id, ''::text as key2, c.id as course_id, c.title as course_title, a.title,
           private.assignment_task_status(s.status::text, a.due_at) as status, a.due_at as task_at, a.due_at,
           null::date as occurrence_date, null::text as policy, 0 as version
      from public.assignments a join courses_ c on c.id = a.course_id
      left join public.submissions s on s.assignment_id = a.id and s.student_id = p_uid
     where a.status = 'published'),
  acts as (
    select 'activity'::text as kind, a.id, o.occurrence_date::text as key2, c.id as course_id, c.title as course_title, a.title,
           case private.occurrence_state(k.status, o.occurrence_date, o.deadline_mode, o.timezone, coalesce(k.due_at, o.due_at))
             when 'completed' then 'done' when 'pending' then 'awaiting_review' when 'rejected' then 'needs_revision'
             when 'open' then 'todo' when 'upcoming' then 'upcoming' else 'missed' end as status,
           coalesce(k.due_at, o.due_at, o.occurrence_date::timestamp at time zone o.timezone) as task_at,
           coalesce(k.due_at, o.due_at) as due_at, o.occurrence_date, a.policy, coalesce(k.version, 0) as version
      from public.activities a join courses_ c on c.id = a.course_id
     cross join lateral private.activity_occurrences(a.id,
            case when p_view = 'range' then p_from_date else (now() at time zone 'UTC')::date - 61 end,
            case when p_view = 'range' then p_to_date - 1
                 when p_view in ('overdue', 'completed') then (now() at time zone 'UTC')::date + 1
                 else (now() at time zone 'UTC')::date + 61 end) o
      left join public.activity_completions k on k.activity_id = a.id and k.student_id = p_uid and k.occurrence_date = o.occurrence_date
     where a.status <> 'archived'),
  ses as (
    select 'attendance_session'::text as kind, s.id, ''::text as key2, c.id as course_id, c.title as course_title, s.title,
           case when s.status = 'closed' then 'held' else 'scheduled' end as status, s.starts_at as task_at, null::timestamptz as due_at,
           null::date as occurrence_date, null::text as policy, 0 as version
      from public.attendance_sessions s join courses_ c on c.id = s.course_id
     where p_view = 'range' and s.starts_at >= p_from and s.starts_at < p_to),
  allr as (select * from asg union all select * from acts union all select * from ses)
  select kind, id, key2, course_id, course_title, title, status, task_at, due_at, occurrence_date, policy, version,
         coalesce(task_at, 'infinity'::timestamptz) as sort_at
    from allr
   where case p_view
           -- date-based occurrences are placed by their own date, instants (deadlines, sessions) by the instant window
           when 'range' then case when kind = 'activity' then occurrence_date >= p_from_date and occurrence_date < p_to_date
                                  else task_at >= p_from and task_at < p_to end
           when 'upcoming' then kind <> 'attendance_session' and status in ('todo', 'needs_revision', 'upcoming')
                                and (kind = 'activity' or task_at is null or task_at >= now() or status = 'needs_revision')
           when 'overdue' then status in ('overdue', 'missed')
           when 'completed' then status in ('done', 'graded', 'awaiting_review')
         end
$$;

create function public.get_my_tasks(
  p_view text, p_from timestamptz default null, p_to timestamptz default null, p_limit integer default 100, p_cursor jsonb default null,
  p_from_date date default null, p_to_date date default null
) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_at timestamptz := (p_cursor ->> 'at')::timestamptz;
  v_kind text := p_cursor ->> 'kind';
  v_id uuid := (p_cursor ->> 'id')::uuid;
  v_key text := p_cursor ->> 'key2';
  v_rows jsonb;
  v_next jsonb;
  v_fd date;
  v_td date;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if not exists (select 1 from public.profiles where id = v_uid and role = 'student') then
    raise exception 'Only students have this view' using errcode = 'PT403'; end if;
  if p_view is null or p_view not in ('range', 'upcoming', 'overdue', 'completed') then
    raise exception 'Unknown view' using errcode = 'PT400'; end if;
  perform private.check_limit(p_limit, 400);
  if p_view = 'range' then
    if p_from is null or p_to is null or p_to <= p_from or p_to - p_from > interval '62 days' then
      raise exception 'The date window must be 1-62 days' using errcode = 'PT400'; end if;
    -- Activity occurrences are calendar dates: callers pass the viewer's local date window; without it the UTC dates of the instants are used.
    v_fd := coalesce(p_from_date, (p_from at time zone 'UTC')::date);
    v_td := coalesce(p_to_date, ((p_to - interval '1 microsecond') at time zone 'UTC')::date + 1);
    if v_td <= v_fd or v_td - v_fd > (case when p_from_date is null and p_to_date is null then 64 else 62 end) then
    raise exception 'The date window must be 1-62 days' using errcode = 'PT400'; end if;
  end if;
  if p_view = 'completed' then
    select coalesce(jsonb_agg(to_jsonb(q) order by q.sort_at desc, q.kind desc, q.id desc, q.key2 desc), '[]'::jsonb) into v_rows from (
      select * from private.student_task_pool(v_uid, p_view, p_from, p_to, v_fd, v_td) t
       where p_cursor is null or (t.sort_at, t.kind, t.id, t.key2) < (v_at, v_kind, v_id, v_key)
       order by t.sort_at desc, t.kind desc, t.id desc, t.key2 desc limit p_limit + 1) q;
  else
    select coalesce(jsonb_agg(to_jsonb(q) order by q.sort_at, q.kind, q.id, q.key2), '[]'::jsonb) into v_rows from (
      select * from private.student_task_pool(v_uid, p_view, p_from, p_to, v_fd, v_td) t
       where p_cursor is null or (t.sort_at, t.kind, t.id, t.key2) > (v_at, v_kind, v_id, v_key)
       order by t.sort_at, t.kind, t.id, t.key2 limit p_limit + 1) q;
  end if;
  if jsonb_array_length(v_rows) > p_limit then
    v_rows := v_rows - p_limit;
    v_next := jsonb_build_object('at', v_rows -> (p_limit - 1) ->> 'sort_at', 'kind', v_rows -> (p_limit - 1) ->> 'kind',
                                 'id', v_rows -> (p_limit - 1) ->> 'id', 'key2', v_rows -> (p_limit - 1) ->> 'key2');
  end if;
  return jsonb_build_object('view', p_view, 'items', v_rows, 'next_cursor', v_next, 'server_time', now());
end $$;

-- Teacher calendar: assignment due dates, per-day activity workload and attendance sessions of owned courses.
create function public.get_teacher_calendar(
  p_from timestamptz, p_to timestamptz, p_limit integer default 100, p_cursor jsonb default null,
  p_from_date date default null, p_to_date date default null
) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_at timestamptz := (p_cursor ->> 'at')::timestamptz;
  v_kind text := p_cursor ->> 'kind';
  v_id uuid := (p_cursor ->> 'id')::uuid;
  v_key text := p_cursor ->> 'key2';
  v_rows jsonb;
  v_next jsonb;
  v_pending integer;
  v_fd date;
  v_td date;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if not exists (select 1 from public.profiles where id = v_uid and role = 'teacher') then
    raise exception 'Only teachers have this view' using errcode = 'PT403'; end if;
  perform private.check_limit(p_limit, 400);
  if p_from is null or p_to is null or p_to <= p_from or p_to - p_from > interval '62 days' then
    raise exception 'The date window must be 1-62 days' using errcode = 'PT400'; end if;
  v_fd := coalesce(p_from_date, (p_from at time zone 'UTC')::date);
  v_td := coalesce(p_to_date, ((p_to - interval '1 microsecond') at time zone 'UTC')::date + 1);
  if v_td <= v_fd or v_td - v_fd > (case when p_from_date is null and p_to_date is null then 64 else 62 end) then
    raise exception 'The date window must be 1-62 days' using errcode = 'PT400'; end if;
  select count(*) into v_pending
    from public.activity_completions c join public.activities a on a.id = c.activity_id join public.courses co on co.id = a.course_id
    join public.course_members m on m.course_id = a.course_id and m.student_id = c.student_id and m.status = 'active'
   where co.owner_id = v_uid and c.status = 'pending';

  with mine as (select id, title, status from public.courses where owner_id = v_uid and status = 'active'),
  asg as (
    select 'assignment_due'::text as kind, a.id, ''::text as key2, m.id as course_id, m.title as course_title, a.title,
           'due'::text as status, a.due_at as task_at,
           (select count(*) from public.submissions s where s.assignment_id = a.id
               and exists (select 1 from public.course_members cm where cm.course_id = a.course_id and cm.student_id = s.student_id and cm.status = 'active')) as received,
           (select count(*) from public.course_members cm where cm.course_id = a.course_id and cm.status = 'active') as expected,
           0 as pending, null::date as occurrence_date
      from public.assignments a join mine m on m.id = a.course_id
     where a.status = 'published' and a.due_at >= p_from and a.due_at < p_to),
  acts as (
    select 'activity_day'::text as kind, a.id, o.occurrence_date::text as key2, m.id as course_id, m.title as course_title, a.title,
           'scheduled'::text as status,
           coalesce(o.due_at, o.occurrence_date::timestamp at time zone o.timezone) as task_at,
           (select count(*) from public.activity_completions k join public.course_members cm on cm.course_id = a.course_id and cm.student_id = k.student_id and cm.status = 'active'
             where k.activity_id = a.id and k.occurrence_date = o.occurrence_date and k.status in ('self_reported', 'teacher_marked', 'approved')) as received,
           (select count(*) from public.course_members cm where cm.course_id = a.course_id and cm.status = 'active') as expected,
           (select count(*) from public.activity_completions k join public.course_members cm on cm.course_id = a.course_id and cm.student_id = k.student_id and cm.status = 'active'
             where k.activity_id = a.id and k.occurrence_date = o.occurrence_date and k.status = 'pending') as pending,
           o.occurrence_date
      from public.activities a join mine m on m.id = a.course_id
     cross join lateral private.activity_occurrences(a.id, v_fd, v_td - 1) o
     where a.status <> 'archived'),
  ses as (
    select 'attendance_session'::text as kind, s.id, ''::text as key2, m.id as course_id, m.title as course_title, s.title,
           case when s.status = 'closed' then 'held' else 'scheduled' end as status, s.starts_at as task_at,
           0::bigint as received, 0::bigint as expected, 0::bigint as pending, null::date as occurrence_date
      from public.attendance_sessions s join mine m on m.id = s.course_id
     where s.starts_at >= p_from and s.starts_at < p_to),
  allr as (select * from asg union all select * from acts union all select * from ses),
  pool as (select *, task_at as sort_at from allr
            where case when kind = 'activity_day' then occurrence_date >= v_fd and occurrence_date < v_td else task_at >= p_from and task_at < p_to end)
  select coalesce(jsonb_agg(to_jsonb(q) order by q.sort_at, q.kind, q.id, q.key2), '[]'::jsonb) into v_rows from (
    select * from pool t where p_cursor is null or (t.sort_at, t.kind, t.id, t.key2) > (v_at, v_kind, v_id, v_key)
     order by t.sort_at, t.kind, t.id, t.key2 limit p_limit + 1) q;
  if jsonb_array_length(v_rows) > p_limit then
    v_rows := v_rows - p_limit;
    v_next := jsonb_build_object('at', v_rows -> (p_limit - 1) ->> 'sort_at', 'kind', v_rows -> (p_limit - 1) ->> 'kind',
                                 'id', v_rows -> (p_limit - 1) ->> 'id', 'key2', v_rows -> (p_limit - 1) ->> 'key2');
  end if;
  return jsonb_build_object('items', v_rows, 'next_cursor', v_next, 'pending_verifications', v_pending, 'server_time', now());
end $$;

