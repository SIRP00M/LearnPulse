create function public.complete_activity(
  p_activity_id uuid, p_occurrence_date date, p_request_id uuid, p_expected_version integer default 0, p_note text default ''
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_a public.activities;
  v_o record;
  v_ev public.activity_events;
  v_c public.activity_completions;
  v_note text := btrim(coalesce(p_note, ''));
  v_fp text := md5(concat_ws('|', p_activity_id, p_occurrence_date, p_expected_version, btrim(coalesce(p_note, ''))));
  v_new text;
  v_action text;
  v_response jsonb;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  if p_request_id is null or p_occurrence_date is null then raise exception 'Request id and date required' using errcode = 'PT400'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_activity_id::text || v_uid::text || p_occurrence_date::text, 0));
  select a.* into v_a from public.activities a join public.course_members m on m.course_id = a.course_id
   where a.id = p_activity_id and m.student_id = v_uid and m.status = 'active' and a.status <> 'archived';
  if not found then raise exception 'Activity not found' using errcode = 'PT404'; end if;
  select * into v_ev from public.activity_events where request_id = p_request_id;
  if found then
    if v_ev.actor_id <> v_uid or v_ev.fingerprint <> v_fp or v_ev.action not in ('self_completed', 'submitted') then
      raise exception 'Request id was already used for different content' using errcode = 'PT409'; end if;
    return v_ev.response || jsonb_build_object('replayed', true);
  end if;
  if char_length(v_note) > 500 then raise exception 'Note is too long' using errcode = 'PT400'; end if;
  if v_a.policy = 'teacher_marked' then
    raise exception 'Your teacher records this activity' using errcode = 'PT403'; end if;
  if v_a.status <> 'active' or not exists (select 1 from public.courses where id = v_a.course_id and status = 'active') then
    raise exception 'This activity is not accepting completions' using errcode = 'PT409'; end if;
  select * into v_o from private.resolve_occurrence(p_activity_id, p_occurrence_date);
  if not found then raise exception 'Not a scheduled day for this activity' using errcode = 'PT409'; end if;
  if p_occurrence_date > (now() at time zone v_o.timezone)::date then
    raise exception 'This occurrence is in the future' using errcode = 'PT409'; end if;
  if v_o.deadline_mode <> 'none' and now() > v_o.due_at then
    raise exception 'The deadline has passed' using errcode = 'PT409'; end if;

  v_new := case v_a.policy when 'self_reported' then 'self_reported' else 'pending' end;
  v_action := case v_a.policy when 'self_reported' then 'self_completed' else 'submitted' end;
  select * into v_c from public.activity_completions
   where activity_id = p_activity_id and student_id = v_uid and occurrence_date = p_occurrence_date for update;
  if found then
    if v_c.version <> p_expected_version then raise exception 'This item changed; reload' using errcode = 'PT409'; end if;
    if v_c.status not in ('rejected', 'not_done') then
      raise exception 'This occurrence is already recorded' using errcode = 'PT409'; end if;
    update public.activity_completions
       set status = v_new, submitted_at = now(), decided_by = null, decided_at = null, reason = '', note = v_note,
           schedule_version = v_o.schedule_version, due_at = v_o.due_at, version = version + 1, updated_at = now()
     where activity_id = p_activity_id and student_id = v_uid and occurrence_date = p_occurrence_date returning * into v_c;
  else
    if p_expected_version <> 0 then raise exception 'This item changed; reload' using errcode = 'PT409'; end if;
    insert into public.activity_completions (activity_id, student_id, occurrence_date, status, schedule_version, due_at, submitted_at, note)
    values (p_activity_id, v_uid, p_occurrence_date, v_new, v_o.schedule_version, v_o.due_at, now(), v_note) returning * into v_c;
  end if;
  v_response := jsonb_build_object('activity_id', p_activity_id, 'occurrence_date', p_occurrence_date, 'status', v_c.status,
                                   'version', v_c.version, 'submitted_at', v_c.submitted_at);
  insert into public.activity_events (activity_id, student_id, occurrence_date, actor_id, action, new_status, note, version_after,
                                      fingerprint, request_id, response)
  values (p_activity_id, v_uid, p_occurrence_date, v_uid, v_action, v_c.status, v_note, v_c.version, v_fp, p_request_id, v_response);
  return v_response;
end $$;

