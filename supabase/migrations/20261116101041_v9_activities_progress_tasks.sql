-- Teacher: the verification queue, oldest first, keyset-paginated (page <= 50).
create function public.get_pending_verifications(p_course_id uuid default null, p_limit integer default 50, p_cursor jsonb default null)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_at timestamptz := (p_cursor ->> 'submitted_at')::timestamptz;
  v_aid uuid := (p_cursor ->> 'activity_id')::uuid;
  v_sid uuid := (p_cursor ->> 'student_id')::uuid;
  v_d date := (p_cursor ->> 'date')::date;
  v_rows jsonb;
  v_next jsonb;
  v_total integer;
begin
  if v_uid is null then raise exception 'Not authenticated' using errcode = 'PT401'; end if;
  perform private.check_limit(p_limit, 50);
  if p_course_id is not null and not exists (select 1 from public.courses where id = p_course_id and owner_id = v_uid) then
    raise exception 'Course not found' using errcode = 'PT404'; end if;
  select count(*) into v_total
    from public.activity_completions c join public.activities a on a.id = c.activity_id join public.courses co on co.id = a.course_id
    join public.course_members m on m.course_id = a.course_id and m.student_id = c.student_id and m.status = 'active'
   where co.owner_id = v_uid and c.status = 'pending' and (p_course_id is null or a.course_id = p_course_id);
  select coalesce(jsonb_agg(to_jsonb(q) order by q.submitted_at, q.activity_id, q.student_id, q.occurrence_date), '[]'::jsonb) into v_rows from (
    select c.activity_id, a.course_id, co.title as course_title, a.title as activity_title, c.student_id, p.full_name, c.occurrence_date,
           c.submitted_at, c.note, c.version, c.due_at
      from public.activity_completions c join public.activities a on a.id = c.activity_id join public.courses co on co.id = a.course_id
      join public.course_members m on m.course_id = a.course_id and m.student_id = c.student_id and m.status = 'active'
      join public.profiles p on p.id = c.student_id
     where co.owner_id = v_uid and c.status = 'pending' and (p_course_id is null or a.course_id = p_course_id)
       and (p_cursor is null or (c.submitted_at, c.activity_id, c.student_id, c.occurrence_date) > (v_at, v_aid, v_sid, v_d))
     order by c.submitted_at, c.activity_id, c.student_id, c.occurrence_date limit p_limit + 1) q;
  if jsonb_array_length(v_rows) > p_limit then
    v_rows := v_rows - p_limit;
    v_next := jsonb_build_object('submitted_at', v_rows -> (p_limit - 1) ->> 'submitted_at', 'activity_id', v_rows -> (p_limit - 1) ->> 'activity_id',
                                 'student_id', v_rows -> (p_limit - 1) ->> 'student_id', 'date', v_rows -> (p_limit - 1) ->> 'occurrence_date');
  end if;
  return jsonb_build_object('items', v_rows, 'next_cursor', v_next, 'total', v_total);
end $$;

-- Progress (one student, one course). Factual figures only; the same builder serves teacher and student.
create function private.build_student_progress(p_course_id uuid, p_student_id uuid) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  v_course public.courses;
  v_member public.course_members;
  v_name text;
  v_att jsonb;
  v_asg jsonb;
  v_act jsonb;
begin
  select * into v_course from public.courses where id = p_course_id;
  select * into v_member from public.course_members where course_id = p_course_id and student_id = p_student_id;
  select full_name into v_name from public.profiles where id = p_student_id;

  select jsonb_build_object(
      'sessions_total', count(*), 'sessions_closed', count(*) filter (where s.status = 'closed'),
      'present', count(*) filter (where r.status = 'present'), 'late', count(*) filter (where r.status = 'late'),
      'excused', count(*) filter (where r.status = 'excused'), 'absent', count(*) filter (where r.status = 'absent'),
      'unmarked', count(*) filter (where r.status is null),
      'rate', case when count(*) filter (where r.status in ('present', 'late', 'absent')) = 0 then null
                   else round(100.0 * count(*) filter (where r.status in ('present', 'late'))
                              / count(*) filter (where r.status in ('present', 'late', 'absent')), 1) end,
      'recent', (select coalesce(jsonb_agg(jsonb_build_object('session_id', x.id, 'title', x.title, 'starts_at', x.starts_at,
                                                               'closed', x.status = 'closed', 'status', x.rstatus) order by x.starts_at desc), '[]'::jsonb)
                   from (select s2.id, s2.title, s2.starts_at, s2.status, r2.status as rstatus
                           from public.attendance_sessions s2
                           left join public.attendance_records r2 on r2.session_id = s2.id and r2.student_id = p_student_id
                          where s2.course_id = p_course_id order by s2.starts_at desc limit 20) x))
    into v_att
    from public.attendance_sessions s
    left join public.attendance_records r on r.session_id = s.id and r.student_id = p_student_id
   where s.course_id = p_course_id;

  with work as (
    select a.id, a.title, a.due_at, a.max_score, s.status as sub_status, s.score
      from public.assignments a left join public.submissions s on s.assignment_id = a.id and s.student_id = p_student_id
     where a.course_id = p_course_id and a.status = 'published')
  select jsonb_build_object(
      'published', count(*), 'done', count(*) filter (where sub_status in ('submitted', 'graded')),
      'awaiting_review', count(*) filter (where sub_status = 'submitted'), 'graded', count(*) filter (where sub_status = 'graded'),
      'needs_revision', count(*) filter (where sub_status = 'returned'), 'not_started', count(*) filter (where sub_status is null),
      'overdue', count(*) filter (where due_at < now() and sub_status is null),
      'average_percent', round(avg(100.0 * score / max_score) filter (where sub_status = 'graded'), 1),
      'items_total', count(*),
      'items', (select coalesce(jsonb_agg(jsonb_build_object('id', y.id, 'title', y.title, 'due_at', y.due_at, 'max_score', y.max_score,
                                         'score', y.score, 'status', private.assignment_task_status(y.sub_status::text, y.due_at))
                                         order by y.due_at desc nulls last, y.id), '[]'::jsonb)
                  from (select * from work order by due_at desc nulls last, id limit 100) y))
    into v_asg from work;

  select jsonb_build_object(
      'activities', coalesce(jsonb_agg(jsonb_build_object('activity_id', a.id, 'title', a.title, 'policy', a.policy, 'status', a.status,
                                                          'streak', private.activity_streak(a.id, p_student_id)) order by a.created_at, a.id), '[]'::jsonb),
      'pending_verification', (select count(*) from public.activity_completions c join public.activities a2 on a2.id = c.activity_id
                                where a2.course_id = p_course_id and c.student_id = p_student_id and c.status = 'pending'))
    into v_act from public.activities a where a.course_id = p_course_id and a.status <> 'archived';

  return jsonb_build_object(
    'course', jsonb_build_object('id', p_course_id, 'title', v_course.title, 'status', v_course.status),
    'student', jsonb_build_object('id', p_student_id, 'full_name', v_name),
    'enrollment', jsonb_build_object('status', v_member.status, 'joined_at', v_member.joined_at),
    'attendance', v_att, 'assignments', v_asg, 'activities', v_act, 'generated_at', now());
end $$;

