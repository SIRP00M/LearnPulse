// Writes dist/_headers (Cloudflare Pages) with a CSP locked to this app's own origin and the configured Supabase project.
// Usage: node scripts/write-headers.mjs   (reads VITE_SUPABASE_URL from the environment or .env.local)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

function envValue(name) {
  if (process.env[name]) return process.env[name];
  for (const f of ['.env.production.local', '.env.local', '.env']) {
    if (!existsSync(f)) continue;
    const m = readFileSync(f, 'utf8').split(/\r?\n/).find((l) => l.startsWith(name + '='));
    if (m) return m.slice(name.length + 1).trim();
  }
  return '';
}

const url = envValue('VITE_SUPABASE_URL');
let origin;
try { origin = new URL(url).origin; } catch { console.error('VITE_SUPABASE_URL is missing or invalid'); process.exit(1); }

const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'", // React inline style attributes and Radix's scroll-lock style element
  "img-src 'self' data: blob:",
  "font-src 'self'",
  `connect-src 'self' ${origin}`,
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const headers = `# Generated by scripts/write-headers.mjs — do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/index.html
  Cache-Control: no-cache

/
  Cache-Control: no-cache
`;
const out = process.env.DIST ?? 'dist';
writeFileSync(`${out}/_headers`, headers);
console.log(`${out}/_headers written (connect-src ${origin})`);
